/**
 * Electrical power generation and storage.
 *
 * The headline advantage claimed for orbital datacenters is "free continuous
 * solar power". Two-thirds of that is true. Sunlight above the atmosphere is
 * about 1361 W/m^2 against roughly 200 W/m^2 annual-average at a good
 * terrestrial site, so the resource really is 6-7x better per unit area. But
 * "continuous" depends entirely on the orbit: a 500 km equatorial orbit is in
 * shadow for 36% of every 95-minute lap, and the battery mass needed to ride
 * through that is not small.
 *
 * A dawn-dusk sun-synchronous orbit avoids eclipse almost entirely for much of
 * the year -- which is why it keeps coming up in these proposals -- at the
 * cost of a thermal environment where the radiators never get a break.
 */

